// Build the two JavaScript artifacts of the dsh-meow-push plugin with esbuild:
//   lib/index.js      — Host half mounted by the Loader (ESM, Node 20+)
//   lib/internals.js  — re-exported pure pieces for tests and embedders
//
// Usage:
//   node scripts/build.mjs
//   ESBUILD_MODULE=file:///path/to/node_modules/esbuild/lib/main.js node scripts/build.mjs
//
// The package ships no runtime dependencies, so nothing is left external: the
// emitted files are self-contained and import only Node built-ins (none today).
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const libDir = path.join(root, 'lib')

/** candidate esbuild module specifiers, in priority order */
function candidates() {
  const list = []
  if (process.env.ESBUILD_MODULE) list.push(process.env.ESBUILD_MODULE)
  list.push('esbuild')
  list.push(pathToFileURL(path.join(root, 'node_modules', 'esbuild', 'lib', 'main.js')).href)
  return list
}

/** Load the first importable esbuild build. */
async function loadEsbuild() {
  const failures = []
  for (const candidate of candidates()) {
    try {
      return await import(candidate)
    } catch (error) {
      failures.push(`${candidate}: ${error instanceof Error ? error.message : String(error)}`)
    }
  }
  throw new Error(
    'esbuild is required to build this plugin and none of these specifiers resolved:\n' +
      failures.map((line) => `  - ${line}`).join('\n') +
      '\nInstall esbuild in this package (npm i --no-save esbuild) or point ESBUILD_MODULE at an ' +
      'existing node_modules/esbuild/lib/main.js URL.',
  )
}

const { build } = await loadEsbuild()

await fs.rm(libDir, { recursive: true, force: true })
await fs.mkdir(libDir, { recursive: true })

/** One ESM bundle, Node 20 target, no external imports. */
async function bundle(entry, outfile) {
  await build({
    entryPoints: [path.join(root, entry)],
    outfile: path.join(libDir, outfile),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    sourcemap: false,
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: '// generated by dsh-meow-push/scripts/build.mjs — do not edit' },
  })
}

await bundle('src/index.ts', 'index.js')
await bundle('src/internals.ts', 'internals.js')

for (const file of ['index.js', 'internals.js']) {
  const stats = await fs.stat(path.join(libDir, file))
  console.log(`[dsh-meow-push] lib/${file} — ${(stats.size / 1024).toFixed(1)} KiB`)
}
